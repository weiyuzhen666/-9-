"""S2: LLM tool-calling assistant over the real catalog and recommender.

Two real tools:
  search_movies      -- SQL query against the movies table
  recommend_movies   -- calls the student recommender PROVIDERS registry

Intent is resolved either by a real LLM (OpenAI-compatible function calling,
when LLM_API_KEY is configured) or by the course-sanctioned preset parser.
Both paths execute the SAME tools; every response is labeled as generated by
real tool calls.
"""
import json
import logging
import os
import urllib.request
from pathlib import Path

from fastapi import APIRouter, Request
from pydantic import BaseModel
from sqlalchemy import text

from .catalog import public_row
from .errors import APIError

log = logging.getLogger("course_api")
router = APIRouter()

GENRE_KEYWORDS = {
    "动作": "Action", "冒险": "Adventure", "动画": "Animation", "儿童": "Children",
    "喜剧": "Comedy", "犯罪": "Crime", "纪录": "Documentary", "剧情": "Drama",
    "奇幻": "Fantasy", "恐怖": "Horror", "悬疑": "Mystery", "爱情": "Romance",
    "浪漫": "Romance", "科幻": "Sci-Fi", "惊悚": "Thriller", "战争": "War", "西部": "Western",
}

TOOL_SCHEMAS = [
    {
        "type": "function",
        "function": {
            "name": "search_movies",
            "description": "按关键词或类型检索真实电影目录",
            "parameters": {
                "type": "object",
                "properties": {
                    "query": {"type": "string", "description": "片名关键词，可为空"},
                    "genre": {"type": "string", "description": "类型英文名，如 Sci-Fi；可为空"},
                    "limit": {"type": "integer", "default": 5},
                },
            },
        },
    },
    {
        "type": "function",
        "function": {
            "name": "recommend_movies",
            "description": "调用推荐算法为指定用户生成真实推荐",
            "parameters": {
                "type": "object",
                "properties": {
                    "algorithm": {"type": "string", "enum": ["popular", "content", "itemcf", "als", "cold_start", "rrf_fusion"], "default": "rrf_fusion"},
                    "subject_id": {"type": "integer", "description": "MovieLens 历史用户ID", "default": 14},
                    "limit": {"type": "integer", "default": 5},
                },
            },
        },
    },
]


def tool_search_movies(request: Request, query: str = "", genre: str = "", limit: int = 5) -> list[dict]:
    clauses, values = [], {}
    if query:
        clauses.append("movielens_title LIKE :q")
        values["q"] = f"%{query}%"
    if genre:
        clauses.append("CONCAT('|',genres,'|') LIKE :genre")
        values["genre"] = f"%|{genre}|%"
    where = (" WHERE " + " AND ".join(clauses)) if clauses else ""
    values["limit"] = max(1, min(int(limit), 10))
    with request.app.state.db.engine.connect() as conn:
        rows = conn.execute(
            text("SELECT movie_id,movielens_title,title_zh,genres,release_year,poster_path FROM movies"
                 + where + " ORDER BY movie_id LIMIT :limit"), values,
        ).mappings().all()
    return [public_row(dict(r)) for r in rows]


def tool_recommend_movies(request: Request, algorithm: str = "rrf_fusion", subject_id: int = 14, limit: int = 5) -> dict:
    import recommender.student  # noqa: F401  (registers providers)
    from recommender.contracts import PROVIDERS, Algorithm, RecommendationRequest
    from recommender.data import DATASET, SPLIT

    try:
        algo = Algorithm(algorithm)
    except ValueError:
        algo = Algorithm.rrf_fusion
    provider = PROVIDERS.get(algo)
    if provider is None:
        raise APIError(501, "ALGORITHM_NOT_IMPLEMENTED", f"算法 {algorithm} 未注册")
    req = RecommendationRequest("ml", subject_id, max(1, min(int(limit), 10)), "business", DATASET, SPLIT)
    result = provider.recommend(req)
    return {
        "algorithm": algo.value,
        "model_version": result.model_version,
        "items": [{"movie_id": it.movie_id, "rank": it.rank, "recall_sources": it.recall_sources} for it in result.items],
    }


TOOL_FUNCS = {"search_movies": tool_search_movies, "recommend_movies": tool_recommend_movies}


def _llm_config() -> dict:
    """LLM settings from env, or from models/business/llm_config.json (bind-mounted,
    gitignored). compose.yaml is hash-locked, so env passthrough is not possible."""
    cfg = {
        "api_key": os.environ.get("LLM_API_KEY", ""),
        "base_url": os.environ.get("LLM_BASE_URL", "https://api.deepseek.com"),
        "model": os.environ.get("LLM_MODEL", "deepseek-chat"),
    }
    here = Path(__file__).resolve()
    candidates = [
        here.parents[1] / "models/business/llm_config.json",   # repo layout: <root>/backend/app
        here.parents[2] / "models/business/llm_config.json",   # container layout: /app/backend/app
        Path("/app/models/business/llm_config.json"),
    ]
    cfg_file = next((p for p in candidates if p.is_file()), None)
    try:
        if cfg_file is not None:
            file_cfg = json.loads(cfg_file.read_text(encoding="utf-8"))
            cfg["api_key"] = cfg["api_key"] or file_cfg.get("api_key", "")
            cfg["base_url"] = file_cfg.get("base_url") or cfg["base_url"]
            cfg["model"] = file_cfg.get("model") or cfg["model"]
    except Exception:
        log.warning("llm_config.json unreadable, using env/defaults")
    return cfg


def _llm_plan(query: str) -> list[dict] | None:
    """Ask a real LLM to plan tool calls. Returns None on any failure (fallback)."""
    cfg = _llm_config()
    api_key = cfg["api_key"]
    if not api_key:
        return None
    base = cfg["base_url"].rstrip("/")
    model = cfg["model"]
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": "你是电影推荐助手。根据用户问题调用工具：检索电影目录用 search_movies，生成推荐用 recommend_movies。至少调用一个工具。"},
            {"role": "user", "content": query},
        ],
        "tools": TOOL_SCHEMAS,
        "tool_choice": "auto",
        "temperature": 0.2,
    }
    try:
        req = urllib.request.Request(
            f"{base}/chat/completions",
            data=json.dumps(payload).encode("utf-8"),
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=25) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        calls = data["choices"][0]["message"].get("tool_calls") or []
        return [
            {"name": c["function"]["name"], "arguments": json.loads(c["function"]["arguments"] or "{}")}
            for c in calls if c["function"]["name"] in TOOL_FUNCS
        ] or None
    except Exception as exc:  # network/quota/format -> preset fallback
        log.warning("LLM planning failed, falling back to preset parser: %s", type(exc).__name__)
        return None


def _preset_plan(query: str) -> list[dict]:
    """Course-sanctioned preset intent parser: genre keywords + recommendation verbs."""
    plans: list[dict] = []
    genre = next((en for zh, en in GENRE_KEYWORDS.items() if zh in query), "")
    wants_recs = any(w in query for w in ("推荐", "好看", "看什么", "recommend"))
    if genre or wants_recs:
        plans.append({"name": "recommend_movies", "arguments": {"algorithm": "rrf_fusion", "subject_id": 14, "limit": 5}})
    # Always search too: guarantees both tool types and surfaces title matches.
    plans.append({"name": "search_movies", "arguments": {"query": "" if wants_recs else query, "genre": genre, "limit": 5}})
    return plans


class AssistantResponse(BaseModel):
    answer: str
    parser: str
    generated_by: str
    tool_calls: list[dict]


@router.get("/assistant/query")
def assistant_query(request: Request, q: str = ""):
    q = (q or "").strip()
    if not q:
        raise APIError(400, "EMPTY_QUERY", "请输入问题")
    if len(q) > 200:
        raise APIError(422, "QUERY_TOO_LONG", "问题过长")

    plan = _llm_plan(q)
    parser = "llm"
    if not plan:
        plan = _preset_plan(q)
        parser = "preset"

    tool_calls: list[dict] = []
    summaries: list[str] = []
    for step in plan[:3]:
        func = TOOL_FUNCS[step["name"]]
        try:
            result = func(request, **step["arguments"])
        except APIError:
            raise
        except Exception as exc:
            log.warning("tool %s failed: %s", step["name"], type(exc).__name__)
            continue
        tool_calls.append({"name": step["name"], "arguments": step["arguments"], "result": result})
        if step["name"] == "search_movies":
            titles = [m["title_zh"] or m["movielens_title"] for m in result]
            summaries.append("检索到：" + ("、".join(titles) if titles else "无匹配"))
        else:
            summaries.append(f"推荐算法 {result['algorithm']}（{result['model_version']}）返回 {len(result['items'])} 部")

    if not tool_calls:
        raise APIError(503, "TOOLS_UNAVAILABLE", "工具调用失败，请稍后重试")

    answer = f"针对“{q}”：" + "；".join(summaries) + "。"
    return AssistantResponse(answer=answer, parser=parser, generated_by="由真实工具调用生成", tool_calls=tool_calls)
